test('死九报扎、付分、切换下局玩法和本地回放', async ({ page }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  const remote: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/\/(?:api|ws)\//.test(request.url())) remote.push(request.url()) })
  await page.goto('/?theme=llmAnime&quality=low')
  await expect(page.locator('main')).toHaveAttribute('data-table-theme','llm')
  await page.getByRole('button', { name: /玩法 活杠/ }).click()
  await page.getByRole('radio', { name: /死九/ }).check()
  await page.getByRole('checkbox', { name: /小牌禁胡/ }).check()
  await page.getByRole('button', { name: '确定', exact: true }).click()
  const start = page.getByRole('button', { name: /开始对局/ })
  await clickWithSeed(start, 9890) // 庄家起手三张六筒。
  const hud = page.locator('.game-table-hud')
  await expect(hud).toHaveAttribute('data-concealed-counts', '14,13,13,13', { timeout: 35_000 })
  await expect(page.getByRole('button', { name: '本局亮牌' })).toContainText('六筒')
  await page.getByRole('button', { name: '扎亮牌 ×3' }).click()
  const result = page.getByRole('dialog', { name: /你 · 扎亮牌/ })
  await expect(result).toContainText('+90')
  await expect(result.locator('.round-rankings em').allTextContents()).resolves.toEqual(['+90','-30','-30','-30'])
  await result.getByRole('button', { name: /下局玩法/ }).click()
  await page.getByRole('radio', { name: /活杠/ }).check()
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await clickWithSeed(result.getByRole('button', { name: '继续' }), 1)
  await expect(page.locator('.round-info')).toContainText('第 2 局 · 活杠')
  await expect(page.locator('.user-identity .dealer-badge')).toBeVisible()
  await expect(page.locator('.hand-rack.playable')).toBeVisible({ timeout: 35_000 })
  await page.locator('.hand-rack.playable .mahjong-tile').first().click()
  await expect(hud).not.toHaveAttribute('data-discard-counts', '0,0,0,0')
  await page.getByRole('button', { name: /开启机器人托管/ }).click()
  await expect(page.getByRole('button', { name: /取消机器人托管/ })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '退出对局' }).click()
  await page.getByRole('button', { name: /对局回放/ }).click()
  await expect(page.getByText(/颍州扎杠麻将 · 4 局场/)).toBeVisible()
  await page.getByRole('button', { name: '查看', exact: true }).click()
  await expect(page.locator('.replay-game-name')).toContainText('颍州扎杠麻将')
  await page.keyboard.press('End')
  await expect(page.getByTestId('replay-result')).toContainText('扎亮牌')
  expect(remote).toEqual([])
  expect(errors).toEqual([])
})

test('横屏在同面普通牌中识别并打出死九的标记补牌', async ({ page }, testInfo) => {
  test.setTimeout(60_000)
  await page.setViewportSize({ width: 844, height: 390 })
  await page.goto('/?quality=low')
  await expect(page.getByRole('button', { name: /开始对局/ })).toBeInViewport()
  await page.getByRole('button', { name: /玩法 活杠/ }).click()
  await page.getByRole('radio', { name: /死九/ }).check()
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await clickWithSeed(page.getByRole('button', { name: /开始对局/ }), 2063)
  const hud = page.locator('.game-table-hud')
  const kong = page.getByRole('button', { name: '暗杠 七筒' })
  await expect(kong).toBeVisible({ timeout: 35_000 })
  const before = await hud.getAttribute('data-wall-count')
  await kong.click()
  await expect(hud).toHaveAttribute('data-wall-count', before!)
  const hand = page.locator('.hand-rack')
  await expect(hand.getByRole('button', { name: '九筒', exact: true })).toHaveCount(2)
  const marked = hand.getByRole('button', { name: '九筒，杠后标记牌' })
  await expect(marked).toBeInViewport()
  await expect(page.getByRole('button', { name: /扎九 ×/ })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('marked-nine-landscape.png') })
  await marked.click()
  await expect(hud).toHaveAttribute('data-discard-counts', /^1,/)
  await expect(marked).toHaveCount(0)
})
